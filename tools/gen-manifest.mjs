#!/usr/bin/env node

import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const packagePath = resolve(root, "package.json");
const curatedPath = resolve(here, "manifest.curated.json");
const outputPath = resolve(root, "docs", "blocks.system.manifest.json");

const packageData = JSON.parse(await readFile(packagePath, "utf8"));
const curated = JSON.parse(await readFile(curatedPath, "utf8"));
delete curated._comment;

const moduleUrl = pathToFileURL(resolve(root, "blocks.system.mjs"));
moduleUrl.searchParams.set("manifest", Date.now());
const { system } = await import(moduleUrl.href);

const exampleEntries = await readdir(resolve(root, "examples"), { withFileTypes: true });
const examples = exampleEntries
  .filter(function (entry) { return entry.isDirectory(); })
  .map(function (entry) { return entry.name; })
  .sort();

const manifest = {
  $schema_note: "Generated by tools/gen-manifest.mjs. Do not hand-edit. Package version, ESM API and examples are derived from the repository; descriptive rules come from tools/manifest.curated.json.",
  version: packageData.version,
  pages_url: "https://seb-prjcts-be.github.io/blocks.system/docs/blocks.system.manifest.json",
  repository: "https://github.com/seb-prjcts-be/blocks.system",
  core_api: Object.keys(system).sort(),
  example_count: examples.length,
  examples,
  ...curated
};

const output = `${JSON.stringify(manifest, null, 2)}\n`;
let previous = null;
try {
  previous = await readFile(outputPath, "utf8");
} catch {
  // First generation.
}

if (previous === output) {
  console.log(`manifest up to date — v${manifest.version}, ${examples.length} examples`);
} else {
  await writeFile(outputPath, output);
  console.log(`manifest written — v${manifest.version}, ${examples.length} examples`);
}
